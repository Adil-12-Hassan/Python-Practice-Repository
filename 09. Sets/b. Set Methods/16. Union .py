# A Program to find the Union of two Sets.

set1 = {1, 2, 3, 4}
set2 = {3, 4, 5, 6}

result = set1.union(set2)

print("Union:", result)

# Explanation:
# The program creates two sets. The union() method combines all unique elements from both sets into a new set. If an element appears in both sets, Python keeps only one copy because sets do not allow duplicates.

# Real-Life Use:
# Union is useful when combining members from different groups or merging unique records from multiple sources.