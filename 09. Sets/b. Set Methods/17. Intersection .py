# A Program to Find the Intersection of two Sets.

set1 = {1, 2, 3, 4}
set2 = {3, 4, 5, 6}

result = set1.intersection(set2)

print("Intersection:", result)

# Explanation:
# The program creates two sets and uses the intersection() method. Python compares both sets and keeps only the elements that are present in both. Elements that exist in only one set are ignored.

# Real-Life Use:
# Intersection is useful for finding common students, shared customers, mutual friends, or overlapping datasets.