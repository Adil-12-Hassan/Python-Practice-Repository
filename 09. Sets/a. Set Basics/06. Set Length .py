# A Program to find the Length of a Set.

fruits = {"Apple", "Banana", "Mango"}

count = len(fruits)
print("Total Elements:", count)

# Explanation:
# The program creates a set and uses the len() function to count the total number of unique elements stored inside it. The returned value is assigned to the variable 'count' and then displayed on the screen.

# Real-Life Use:
# The len() function helps determine how many unique records, users, or products are stored.