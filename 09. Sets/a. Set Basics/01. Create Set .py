# A Program to Create a Set.

fruits = {"Apple", "Banana", "Mango"}

print("Set:", fruits)

# Explanation:
# The program creates a set named 'fruits' containing three unique elements. Unlike a list or tuple, a set automatically stores only unique values. Each value is enclosed inside curly braces {} and separated by commas. When the program runs, Python creates the set in memory and stores the elements without maintaining any fixed order. Finally, the complete set is displayed using the print() function.

# Real-Life Use:
# Sets are useful when you need to store unique items such as usernames, unique product IDs, or unique email addresses.