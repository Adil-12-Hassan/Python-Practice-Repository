# A Program to Remove an Element from a Set.

fruits = {"Apple", "Banana", "Mango"}
print("Before:", fruits)

fruits.remove("Banana")
print("After:", fruits)

# Explanation:
# The program creates a set and then removes the element "Banana" using the remove() method. Python searches for the specified element inside the set. If the element exists, it is removed. The updated set is then displayed. If the element does not exist, Python raises an error.

# Real-Life Use:
# Removing elements is useful when deleting inactive users, completed tasks, or unavailable products.