# A Program to Add an Element to a Set.

fruits = {"Apple", "Banana", "Mango"}

print("Before:", fruits)

fruits.add("Orange")

print("After:", fruits)

# Explanation:
# The program first creates a set containing three fruits. The add() method is then called to insert a new element into the set. Python checks whether the element already exists. If it is new, it is added to the set; otherwise, nothing changes. Finally, the updated set is displayed.

# Real-Life Use:
# The add() method is useful when adding new users, products, or categories while ensuring duplicates are not stored.