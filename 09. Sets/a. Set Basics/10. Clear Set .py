# A Program to Clear All Elements from a Set.

fruits = {"Apple", "Banana", "Mango"}
print("Before:", fruits)

fruits.clear()
print("After:", fruits)

# Explanation:
# The program creates a set containing three elements. The clear() method is then called on the set. Python removes every element stored inside the set, leaving it completely empty. The empty set is then displayed using print().

# Real-Life Use:
# The clear() method is useful when resetting temporary data, clearing caches, or preparing a collection to store new information.