# A Program to Print a Set.

colors = {"Red", "Green", "Blue"}

print("Colors:", colors)

# Explanation:
# The program creates a set named 'colors' and stores three unique color names. The print() function displays all the elements contained in the set. Since sets are unordered collections, the order of the output may be different every time the program runs. This is normal behavior for sets.

# Real-Life Use:
# Printing sets is useful for displaying unique categories, tags, or collections of distinct items.