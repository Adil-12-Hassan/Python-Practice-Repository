# A Program to Iterate through a Set using a For Loop.

fruits = {"Apple", "Banana", "Mango"}

for fruit in fruits:
    print(fruit)

# Explanation:
# The program creates a set and starts a for loop. During each iteration, Python takes one element from the set and stores it in the variable 'fruit'. The loop continues until every unique element has been processed. Since sets are unordered, the elements may not appear in the same order every time.

# Real-Life Use:
# Iterating through sets is useful when processing unique users, categories, or IDs one by one.