# A Program to Analyze Unique Hashtags.

hashtags = {
    "#Python",
    "#AI",
    "#Coding",
    "#Python",
    "#MachineLearning"
}

print("Unique Hashtags:")
print(hashtags)

# Explanation:
# The program stores hashtags inside a set. Duplicate hashtags are removed automatically, leaving only unique values. The final set displays every unique hashtag that appeared.

# Real-Life Use:
# Social media analytics platforms use sets to analyze trending hashtags.