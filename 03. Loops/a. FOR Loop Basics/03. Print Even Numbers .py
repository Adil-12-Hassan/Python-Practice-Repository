# A Program to Print All Even Numbers from 1 to 20.

for number in range(2, 21, 2):
    print(number)
    
# Explanation:
# This code snippet uses a for loop to print all even numbers from 1 to 20. The range function is called with three arguments: the starting number (2), the stopping number (21), and the step (2). The loop iterates through each number in this range, incrementing by 2 on each iteration, and the print function outputs the current even number to the console. This demonstrates how to use a for loop to iterate through a specific sequence of numbers.