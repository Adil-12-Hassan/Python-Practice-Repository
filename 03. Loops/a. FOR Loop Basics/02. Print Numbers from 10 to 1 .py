# A Program to Print Numbers from 10 to 1.

for number in range(10, 0, -1):
    print(number)

# Explanation:
# This code snippet uses a for loop to print numbers from 10 down to 1. The range function is called with three arguments: the starting number (10), the stopping number (0), and the step (-1). The loop iterates through each number in this range, decrementing by 1 on each iteration, and the print function outputs the current number to the console. This demonstrates how to use a for loop to iterate in reverse order.