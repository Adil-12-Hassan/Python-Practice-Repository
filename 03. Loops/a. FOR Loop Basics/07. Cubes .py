# A Program Print the Cube of Numbers from 1 to 10.

for number in range(1, 11):
    print(f"{number}³ = {number ** 3}")
    
# Explanation:
# This code snippet uses a for loop to print the cube of numbers from 1 to 10. The range function generates a sequence of numbers starting from 1 up to (but not including) 11. The loop iterates through each number in this range, and the print function outputs the current number along with its cube (calculated using the exponentiation operator `**`) in a formatted string. This demonstrates how to use a for loop to perform calculations on a sequence of numbers.