# A Program to Print Numbers from 1 to 10.

for number in range(1, 11):
    print(number)
    
# Explanation:
# This code snippet uses a for loop to print numbers from 1 to 10. The range function generates a sequence of numbers starting from 1 up to (but not including) 11. The loop iterates through each number in this range, and the print function outputs the current number to the console. This is a simple example of using a for loop to iterate over a sequence of numbers.
