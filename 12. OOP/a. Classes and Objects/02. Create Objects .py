# A Program to create objects from a class

class Student:
    pass


student1 = Student()
student2 = Student()

print(student1)
print(student2)


# Explanation:
# Student is first created as a class. student1 and student2 are separate objects created from Student. Each object has its own identity in memory. The print statements display the objects created from the class.

# Real-Life Use:
# A single class can represent many real-world entities. For example, Student can create objects for different students.