# Using f-string to Print the value of a variable

name = "Hasher Amin"
age = 20
City = "Faisalabad"

print(f"\nMy name is: {name}")
print(f"My age is: {age}")
print(f"I live in: {City}")

# Explaining the code:
# In the above code, we are using f-strings (formatted string literals) to print the values of the variables. The f-string allows us to embed expressions inside string literals, using curly braces {}. This makes it easier to format strings and include variable values directly within the string.