# Assigning multiple values to multiple variables in one line

name, age, city = "Hasher Amin", 20, "Faisalabad"

print("\nMy name is:", name)
print("My age is:", age)
print("I live in:", city)

# Explaining the code:
# In the above code, we are assigning values to three variables (name, age, city) in a single line. The values are assigned in the order they are listed, so "Hasher Amin" is assigned to name, 20 is assigned to age, and "Faisalabad" is assigned to city. This is a concise way to initialize multiple variables at once.