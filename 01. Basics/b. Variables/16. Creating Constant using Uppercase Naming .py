# Note: Python doesn't have true constants. By convention, uppercase names indicate values that shouldn't be changed.

PI = 3.14159
print("\nThe value of PI is:", PI)

# Explaining the code:
# In the above code, we are creating a constant named 'PI' and assigning it the value of 3.14159. By convention, we use uppercase letters for constant names to indicate that they should not be changed throughout the program. However, Python does not enforce this, and it is still possible to change the value of 'PI' if desired.