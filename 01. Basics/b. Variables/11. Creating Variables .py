# Creating Variables in Python

name = "Hasher Amin"
age = 20
City = "Faisalabad"

print("\nMy name is:", name)
print("My age is:", age)
print("I live in:", City)

# Explaining the code:
# In the above code, we are creating three variables: 'name', 'age', and 'City'. We assign the string "Hasher Amin" to the variable 'name', the integer 20 to the variable 'age', and the string "Faisalabad" to the variable 'City'. We then print the values of these variables using the print() function.