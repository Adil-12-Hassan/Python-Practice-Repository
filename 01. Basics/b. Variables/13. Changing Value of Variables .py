# Changing the Values of the Variables

a = 10
print("\nThe value of a before change is:", a)

# The value of a is changed to 20
a = 20
print("The value of a after change is:", a)

# Explaining the code:
# In the above code, we are first assigning the value 10 to the variable 'a'. We then print the value of 'a' before the change. After that, we change the value of 'a' to 20 and print the value of 'a' after the change. This demonstrates how to change the value of a variable in Python.